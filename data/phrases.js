/** Deterministic phrase of the day (everyday phrases only). */
export function phraseOfTheDay(date = new Date()) {
  const day = Math.floor(date.getTime() / 86400000);
  // simple hash so consecutive days jump around the categories instead of walking one group
  const idx = (day * 37 + 11) % ALL_PHRASES.length;
  return ALL_PHRASES[idx];
}
